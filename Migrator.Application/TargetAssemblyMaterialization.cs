using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;
using Migrator.Core;

namespace Migrator.Application;

public sealed partial class MigrationEngine
{
    /// <summary>
    /// Opt-in, atomic materialization of the exact read-only assembly plan.
    /// Never edits a source tree or overwrites any existing target directory.
    /// An optional real dotnet build/test is a separate evidence stage.
    /// </summary>
    public TargetAssemblyVerification MaterializeTargetAssembly(
        string sourceDirectory,
        string targetDirectory,
        string expectedAnalysisId,
        string expectedCandidateId,
        string? configPath = null,
        bool runBuild = false,
        bool runNUnit = false,
        CancellationToken cancellationToken = default)
    {
        var plan = PlanTargetAssembly(sourceDirectory, configPath,
            expectedAnalysisId, expectedCandidateId, cancellationToken);
        if (plan.Status != "ready_for_build")
            throw new InvalidOperationException("TARGET_ASSEMBLY_PLAN_BLOCKED: "
                + string.Join(" | ", plan.Issues.Select(issue => issue.Code)));

        var targetRoot = Path.GetFullPath(targetDirectory);
        EnsureTargetAssemblyDestination(plan.SourceRoot, targetRoot);
        var parent = Path.GetDirectoryName(targetRoot)
            ?? throw new ArgumentException("TARGET_ASSEMBLY_PARENT_REQUIRED");
        if (!Directory.Exists(parent))
            throw new DirectoryNotFoundException(
                "TARGET_ASSEMBLY_PARENT_MISSING: create the parent outside the source tree.");
        if (Directory.Exists(targetRoot) || File.Exists(targetRoot))
            throw new InvalidOperationException(
                "TARGET_ALREADY_EXISTS: do not overwrite an existing assembly checkout.");

        var stage = Path.Combine(parent, ".migrator-assembly-stage-"
            + Guid.NewGuid().ToString("N"));
        try
        {
            Directory.CreateDirectory(stage);
            foreach (var file in plan.Files)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var name = Path.Combine(stage,
                    file.RelativePath.Replace('/', Path.DirectorySeparatorChar));
                Directory.CreateDirectory(Path.GetDirectoryName(name)!);
                File.WriteAllBytes(name, Encoding.UTF8.GetBytes(file.Content));
            }
            var captured = CaptureAssemblyFiles(stage, cancellationToken);
            if (!CompareAssemblyFileSet(plan, captured, out _))
                throw new InvalidOperationException(
                    "TARGET_ASSEMBLY_STAGE_MISMATCH: generated bytes differ before publication.");
            cancellationToken.ThrowIfCancellationRequested();
            Directory.Move(stage, targetRoot);
        }
        finally
        {
            if (Directory.Exists(stage))
                Directory.Delete(stage, recursive: true);
        }

        return VerifyTargetAssembly(sourceDirectory, targetRoot,
            expectedAnalysisId, expectedCandidateId,
            configPath, runBuild, runNUnit, cancellationToken);
    }

    /// <summary>
    /// Validate every exact source-generated C# file, explicit Compile item,
    /// scoped fixture dependency, project file and manifest before running
    /// any opt-in build or NUnit test. bin/obj/TestResults are explicitly
    /// excluded from the source artifact comparison after real builds.
    /// </summary>
    public TargetAssemblyVerification VerifyTargetAssembly(
        string sourceDirectory,
        string targetDirectory,
        string expectedAnalysisId,
        string expectedCandidateId,
        string? configPath = null,
        bool runBuild = false,
        bool runNUnit = false,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(expectedAnalysisId)
            || string.IsNullOrWhiteSpace(expectedCandidateId))
            throw new ArgumentException(
                "EXPECTED_ASSEMBLY_ANALYSIS_AND_CANDIDATE_REQUIRED");
        var plan = PlanTargetAssembly(sourceDirectory, configPath,
            expectedAnalysisId, expectedCandidateId, cancellationToken);
        var targetRoot = Path.GetFullPath(targetDirectory);
        EnsureTargetAssemblyDestination(plan.SourceRoot, targetRoot);

        var issues = new List<TargetAssemblyIssue>(plan.Issues);
        var tree = new TargetAssemblyStage("blocked", "exact-target-file-set",
            "Target assembly plan is blocked by source or scope diagnostics.");
        var build = new TargetAssemblyStage("not_run", "dotnet-build",
            "dotnet build has not been executed.");
        var runtime = new TargetAssemblyStage("not_run", "nunit-trx",
            "NUnit runtime was not executed.");

        if (plan.Status == "ready_for_build")
        {
            try
            {
                var captured = CaptureAssemblyFiles(targetRoot, cancellationToken);
                if (!CompareAssemblyFileSet(plan, captured, out var mismatch))
                {
                    issues.Add(new("TARGET_ASSEMBLY_FILE_SET_OR_HASH_MISMATCH",
                        "error", mismatch));
                    tree = new TargetAssemblyStage("failed", "exact-target-file-set", mismatch);
                }
                else
                {
                    var project = Path.Combine(targetRoot, plan.ProjectFile);
                    var expectedCompile = plan.Files.Where(file =>
                        file.RelativePath.EndsWith(".cs", StringComparison.Ordinal))
                        .Select(file => file.RelativePath).OrderBy(path => path,
                            StringComparer.Ordinal).ToArray();
                    var csproj = XDocument.Load(project);
                    XNamespace ns = csproj.Root?.Name.Namespace ?? XNamespace.None;
                    var implicitCompile = csproj.Descendants(ns + "EnableDefaultCompileItems")
                        .SingleOrDefault()?.Value;
                    var compiledPaths = csproj.Descendants(ns + "Compile")
                        .Select(node => node.Attribute("Include")?.Value
                            .Replace('\\', '/'))
                        .Where(path => path != null).Select(path => path!)
                        .OrderBy(path => path, StringComparer.Ordinal).ToArray();
                    if (implicitCompile != "false"
                        || !compiledPaths.SequenceEqual(expectedCompile,
                            StringComparer.Ordinal))
                    {
                        issues.Add(new("TARGET_ASSEMBLY_COMPILE_ITEMS_MISMATCH",
                            "error", "Explicit MSBuild Compile items must exactly match the generated "
                            + "C# file set, without SDK glob auto-inclusion."));
                        tree = new TargetAssemblyStage("failed", "explicit-msbuild-compile",
                            "MSBuild compile items differ from the immutable assembly plan.");
                    }
                    else
                    {
                        tree = new TargetAssemblyStage("passed", "exact-content-and-msbuild",
                            $"Verified {expectedCompile.Length} generated C# sources, "
                            + "manifest and explicit SDK compile items.");
                    }
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException
                or System.Xml.XmlException or InvalidOperationException)
            {
                issues.Add(new("TARGET_ASSEMBLY_CAPTURE_FAILED", "error", ex.Message));
                tree = new TargetAssemblyStage("failed", "exact-target-file-set",
                    "Target tree cannot be captured without side effects.");
            }
        }

        if (tree.Status == "passed" && (runBuild || runNUnit))
        {
            build = ExecuteDotNet(targetRoot,
                new[] { "build", plan.ProjectFile, "--configuration", "Release",
                    "--nologo" }, "dotnet-build", cancellationToken);

            if (build.Status == "passed" && runNUnit)
            {
                runtime = ExecuteDotNet(targetRoot,
                    new[] { "test", plan.ProjectFile, "--configuration", "Release",
                        "--no-build", "--no-restore", "--nologo",
                        "--results-directory", "TestResults",
                        "--logger", "trx;LogFileName=migrator-target-assembly.trx" },
                    "nunit-trx", cancellationToken);
                if (runtime.Status == "passed")
                    runtime = ValidateNUnitTrx(targetRoot, runtime, plan.NUnitCases);
            }
            else if (runNUnit)
                runtime = new TargetAssemblyStage("blocked", "nunit-trx",
                    "Cannot execute NUnit tests because the generated target did not build.");
        }
        else if (tree.Status != "passed" && (runBuild || runNUnit))
        {
            build = new TargetAssemblyStage("blocked", "dotnet-build",
                "Exact target file-set verification failed; no build was attempted.");
            if (runNUnit)
                runtime = new TargetAssemblyStage("blocked", "nunit-trx",
                    "NUnit execution requires an intact target tree and a passed build.");
        }

        // Compilation/test may add only ignored obj/bin/TestResults outputs,
        // never mutate the source-locked generated project and fixture files.
        if (tree.Status == "passed")
        {
            try
            {
                var after = CaptureAssemblyFiles(targetRoot, cancellationToken);
                if (!CompareAssemblyFileSet(plan, after, out var mismatch))
                {
                    tree = new TargetAssemblyStage("failed", "exact-target-file-set",
                        "Target artifact changed during build or NUnit execution: " + mismatch);
                    issues.Add(new("TARGET_ASSEMBLY_MUTATED_DURING_VERIFICATION", "error",
                        mismatch));
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                tree = new TargetAssemblyStage("failed", "exact-target-file-set",
                    "Target artifact was inaccessible after build or tests.");
                issues.Add(new("TARGET_ASSEMBLY_MUTATED_DURING_VERIFICATION", "error",
                    ex.Message));
            }
        }

        var sourceAfter = Analyze(plan.SourceRoot, configPath, cancellationToken);
        if (sourceAfter.AnalysisId != plan.AnalysisId)
            throw new InvalidOperationException(
                "SOURCE_CHANGED_DURING_ASSEMBLY_VERIFICATION: reject stale evidence.");

        var status = tree.Status != "passed" ? "blocked"
            : build.Status == "failed" || runtime.Status == "failed" ? "failed"
            : build.Status == "blocked" || runtime.Status == "blocked" ? "blocked"
            : runtime.Status == "passed" ? "runtime_passed_review_required"
            : build.Status == "passed" ? "build_passed_review_required"
            : "materialized_review_required";
        return new TargetAssemblyVerification(
            "migrator-target-assembly-verification/v1alpha1",
            plan.AnalysisId, plan.CandidateId, plan.TargetTreeHash,
            targetRoot, status, tree, build, runtime, issues,
            new[]
            {
                "Exact file-set passed is not evidence of source-to-target behavioral equivalence.",
                "dotnet build passed proves only this generated SDK project compiled with the packages resolved in this environment.",
                "NUnit runtime passed means real tests were executed and counted in TRX, not that product business observables match Selenium.",
                "Browser installation, login data, network access and target application state are not provisioned by this verifier.",
                "Package restore/build and NUnit execution require explicit opt-in; the read-only plan never executes commands."
            });
    }

    private static void EnsureTargetAssemblyDestination(string source, string target)
    {
        if (PathInside(source, target) || PathInside(target, source))
            throw new InvalidOperationException(
                "OVERLAPPING_SOURCE_AND_TARGET: target assembly must be outside the source tree.");
        // Reject symlinked existing ancestors even when the final target
        // directory does not exist yet.
        var current = Path.GetFullPath(target);
        while (!string.IsNullOrEmpty(current))
        {
            if ((Directory.Exists(current) || File.Exists(current))
                && (File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                throw new UnauthorizedAccessException(
                    "TARGET_ASSEMBLY_SYMLINK_REJECTED: target has a symlink ancestor.");
            var parent = Path.GetDirectoryName(current);
            if (parent == null || parent == current) break;
            current = parent;
        }
    }

    private static IReadOnlyList<(string Path, byte[] Bytes)> CaptureAssemblyFiles(
        string directory, CancellationToken cancellationToken)
    {
        if (!Directory.Exists(directory))
            throw new DirectoryNotFoundException("TARGET_ASSEMBLY_ROOT_MISSING");
        var files = new List<(string Path, byte[] Bytes)>();
        long bytes = 0;
        Walk(directory);
        return files.OrderBy(file => file.Path, StringComparer.Ordinal).ToArray();

        void Walk(string path)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if ((File.GetAttributes(path) & FileAttributes.ReparsePoint) != 0)
                throw new UnauthorizedAccessException(
                    "TARGET_ASSEMBLY_SYMLINK_REJECTED");
            foreach (var entry in Directory.EnumerateFileSystemEntries(path)
                         .OrderBy(name => name, StringComparer.Ordinal))
            {
                var attr = File.GetAttributes(entry);
                if ((attr & FileAttributes.ReparsePoint) != 0)
                    throw new UnauthorizedAccessException(
                        "TARGET_ASSEMBLY_SYMLINK_REJECTED");
                if ((attr & FileAttributes.Directory) != 0)
                {
                    if (Path.GetDirectoryName(entry) == directory
                        && Path.GetFileName(entry) is ("bin" or "obj" or "TestResults"))
                        continue;
                    Walk(entry);
                }
                else
                {
                    var relative = Path.GetRelativePath(directory, entry)
                        .Replace('\\', '/');
                    var content = File.ReadAllBytes(entry);
                    bytes += content.Length;
                    files.Add((relative, content));
                    if (files.Count > 132 || bytes > 16 * 1024 * 1024)
                        throw new InvalidOperationException(
                            "TARGET_ASSEMBLY_TOO_LARGE: maximum 132 files / 16 MiB.");
                }
            }
        }
    }

    private static bool CompareAssemblyFileSet(
        TargetAssemblyPlan plan,
        IReadOnlyList<(string Path, byte[] Bytes)> captured,
        out string mismatch)
    {
        var expected = plan.Files.OrderBy(f => f.RelativePath,
            StringComparer.Ordinal).ToArray();
        var actual = captured.OrderBy(f => f.Path, StringComparer.Ordinal).ToArray();
        if (!expected.Select(f => f.RelativePath).SequenceEqual(
                actual.Select(f => f.Path), StringComparer.Ordinal))
        {
            mismatch = "Expected [" + string.Join(", ",
                expected.Select(f => f.RelativePath).Take(20)) + "], found ["
                + string.Join(", ", actual.Select(f => f.Path).Take(20)) + "].";
            return false;
        }
        foreach (var (file, i) in expected.Select((file, i) => (file, i)))
        {
            var hash = Convert.ToHexString(
                SHA256.HashData(actual[i].Bytes)).ToLowerInvariant();
            if (hash != file.Sha256)
            {
                mismatch = "Target bytes changed: " + file.RelativePath;
                return false;
            }
        }
        var hashTree = ContentTreeHasher.ComputeBytes(actual.Select(
            file => (file.Path, file.Bytes)));
        if (hashTree != plan.TargetTreeHash)
        {
            mismatch = "Target tree hash differs from the current plan.";
            return false;
        }
        mismatch = string.Empty;
        return true;
    }

    private static TargetAssemblyStage ExecuteDotNet(
        string workingDirectory, string[] args, string kind,
        CancellationToken cancellationToken)
    {
        try
        {
            var start = new ProcessStartInfo
            {
                FileName = "dotnet",
                WorkingDirectory = workingDirectory,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                CreateNoWindow = true
            };
            foreach (var arg in args) start.ArgumentList.Add(arg);
            start.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
            start.Environment["DOTNET_SKIP_FIRST_TIME_EXPERIENCE"] = "1";
            using var process = Process.Start(start)
                ?? throw new InvalidOperationException("dotnet process did not start.");
            using var timeout = CancellationTokenSource.CreateLinkedTokenSource(
                cancellationToken);
            timeout.CancelAfter(TimeSpan.FromMinutes(4));
            var stdout = process.StandardOutput.ReadToEndAsync(timeout.Token);
            var stderr = process.StandardError.ReadToEndAsync(timeout.Token);
            try
            {
                process.WaitForExitAsync(timeout.Token).GetAwaiter().GetResult();
            }
            catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
            {
                process.Kill(entireProcessTree: true);
                return new TargetAssemblyStage("failed", kind,
                    "dotnet command exceeded the bounded four-minute timeout.");
            }
            var text = stdout.GetAwaiter().GetResult()
                + "\n" + stderr.GetAwaiter().GetResult();
            var summary = text.Length <= 8000 ? text : text[^8000..];
            return new TargetAssemblyStage(process.ExitCode == 0 ? "passed" : "failed",
                kind, summary, process.ExitCode);
        }
        catch (System.ComponentModel.Win32Exception)
        {
            return new TargetAssemblyStage("blocked", kind,
                "dotnet SDK executable is not installed or cannot be started.");
        }
    }

    private static TargetAssemblyStage ValidateNUnitTrx(
        string targetRoot, TargetAssemblyStage command,
        IReadOnlyList<NUnitCaseInventory> plannedCases)
    {
        try
        {
            var file = Path.Combine(targetRoot, "TestResults",
                "migrator-target-assembly.trx");
            if (!File.Exists(file))
                return command with { Status = "failed",
                    Details = "dotnet test exited 0 but no NUnit TRX evidence exists." };
            var root = XDocument.Load(file).Root
                ?? throw new InvalidOperationException("Empty NUnit TRX file.");
            var counters = root.Descendants()
                .FirstOrDefault(node => node.Name.LocalName == "Counters")
                ?? throw new InvalidOperationException("TRX counters missing.");
            int Number(string name) => int.TryParse(
                counters.Attribute(name)?.Value, out var number) ? number : 0;
            var total = Number("total");
            var passed = Number("passed");
            var failed = Number("failed");
            var skipped = Number("notExecuted");
            var expectedRunnable = plannedCases.Count(c => c.RunState == "runnable");
            var expectedDisabled = plannedCases.Count - expectedRunnable;
            // TRX can omit NUnit Explicit cases from its run set. Never
            // treat their absence as execution or successful discovery.
            // A source/target list-tests comparison is required separately.
            if (total < expectedRunnable
                || total > plannedCases.Count
                || passed < expectedRunnable
                || failed > 0
                || skipped > expectedDisabled
                || passed + failed + skipped != total)
                return command with { Status = "failed",
                    Details = $"NUnit TRX rejected: total={total}, passed={passed}, failed={failed}, notExecuted={skipped}; static runnable={expectedRunnable}, disabled={expectedDisabled}.",
                    ExecutedTests = passed + failed, PassedTests = passed };
            return command with { Status = "passed",
                Details = $"Actual NUnit TRX: total={total}, passed={passed}, failed={failed}, notExecuted={skipped}; static runnable={expectedRunnable}, disabled={expectedDisabled}. Explicit discovery and skip reasons require separate NUnit evidence.",
                ExecutedTests = passed + failed, PassedTests = passed };
        }
        catch (Exception ex) when (ex is IOException or System.Xml.XmlException
            or InvalidOperationException)
        {
            return command with { Status = "failed",
                Details = "NUnit TRX cannot be validated: " + ex.Message };
        }
    }
